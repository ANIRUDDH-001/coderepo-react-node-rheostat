// The demo flag catalog: 16 flags across every state the product can show, with a per-environment history.
// `history` entries become FlagVersions (v2, v3, …) in order; every flag also gets v1 (source: create) per environment.

const on = (id) => ({ variationId: id });
const split = (...pairs) => ({ rollout: { bucketBy: "key", weights: pairs.map(([variationId, weight]) => ({ variationId, weight })) } });
const segmentRule = (id, description, segmentKey, serve) => ({
	id,
	description,
	clauses: [{ attribute: "key", operator: "segmentMatch", values: [segmentKey], negate: false }],
	serve,
});
const config = (enabled, offVariationId, fallthrough, rules = []) => ({ enabled, offVariationId, rules, fallthrough });
const boolean = [
	{ id: "v_true", name: "True", value: true },
	{ id: "v_false", name: "False", value: false },
];
const booleanOn = config(true, "v_false", on("v_true"));
const booleanOff = config(false, "v_false", on("v_true"));
// Targeting on while everyone still gets the old behaviour: the baseline a rollout starts from.
const booleanArmed = config(true, "v_false", on("v_false"));
const ramp = (percent) => config(true, "v_false", split(["v_true", percent * 1000], ["v_false", 100000 - percent * 1000]));
const step = (env, daysAgo, actor, source, reason, configuration) => ({ env, daysAgo, actor, source, reason, config: configuration });

